import { useState, useEffect } from 'react'
import { Lightbulb, ChevronLeft, ChevronRight, ShieldCheck, Sparkles, FileText, CheckCircle } from 'lucide-react'
import { Button } from '@/components/ui/button'

export interface TipItem {
  id: number
  title: string
  text: string
  tag: string
  icon: React.ComponentType<{ className?: string }>
}

export const ROTATING_TIPS: TipItem[] = [
  {
    id: 1,
    title: 'Zero-Hallucination Fact Grounding',
    text: 'Every single bullet point generated by LatexAI is strictly anchored to your verified profile achievements. We never hallucinate skills, metrics, or previous employers.',
    tag: 'Traceability',
    icon: ShieldCheck,
  },
  {
    id: 2,
    title: 'Vector-Rendered LaTeX Text',
    text: 'Unlike HTML-to-PDF or Word exports, pdflatex produces pure vector-embedded fonts that enterprise ATS parsers index with 99.8% text extractability.',
    tag: 'ATS Parsing',
    icon: FileText,
  },
  {
    id: 3,
    title: 'The Single-Page Golden Ratio',
    text: 'Recruiters spend an average of 7.4 seconds reviewing an engineering resume. Our typography layout engine dynamically adjusts margins and line leading to keep your document strictly on 1 page.',
    tag: 'Layout',
    icon: CheckCircle,
  },
  {
    id: 4,
    title: 'Quantified Impact Formula',
    text: 'Use the XYZ formula: "Accomplished [X], as measured by [Y], by doing [Z]". Resumes with quantified business outcomes receive up to 40% more interview callbacks.',
    tag: 'Best Practice',
    icon: Sparkles,
  },
  {
    id: 5,
    title: 'Full Source Code Ownership',
    text: 'You own 100% of your generated LaTeX code. Once compilation completes, you can download the clean `.tex` file or edit specific lines directly in our web editor.',
    tag: 'LaTeX Control',
    icon: Lightbulb,
  },
]

interface RotatingTipsProps {
  intervalMs?: number
}

export function RotatingTips({ intervalMs = 5000 }: RotatingTipsProps) {
  const [currentIndex, setCurrentIndex] = useState(0)
  const [isHovered, setIsHovered] = useState(false)

  // Auto-rotation effect
  useEffect(() => {
    if (isHovered) return

    const timer = setInterval(() => {
      setCurrentIndex((prev) => (prev + 1) % ROTATING_TIPS.length)
    }, intervalMs)

    return () => clearInterval(timer)
  }, [isHovered, intervalMs])

  const handleNext = () => {
    setCurrentIndex((prev) => (prev + 1) % ROTATING_TIPS.length)
  }

  const handlePrev = () => {
    setCurrentIndex((prev) => (prev - 1 + ROTATING_TIPS.length) % ROTATING_TIPS.length)
  }

  const currentTip = ROTATING_TIPS[currentIndex]
  const TipIcon = currentTip.icon

  return (
    <div
      className="p-4 rounded-xl border border-border/70 bg-gradient-to-br from-card to-muted/30 shadow-xs space-y-3 relative overflow-hidden"
      onMouseEnter={() => setIsHovered(true)}
      onMouseLeave={() => setIsHovered(false)}
      data-testid="rotating-tips"
    >
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-1.5 text-xs font-semibold text-primary uppercase tracking-wider">
          <Lightbulb className="h-4 w-4 text-amber-500 animate-pulse" />
          <span>ATS &amp; LaTeX Pro Tip</span>
        </div>

        <div className="flex items-center gap-1">
          <span className="text-[10px] font-mono text-muted-foreground mr-1">
            {currentIndex + 1} / {ROTATING_TIPS.length}
          </span>
          <Button
            variant="ghost"
            size="icon"
            className="h-6 w-6 text-muted-foreground hover:text-foreground"
            onClick={handlePrev}
            aria-label="Previous Tip"
          >
            <ChevronLeft className="h-3.5 w-3.5" />
          </Button>
          <Button
            variant="ghost"
            size="icon"
            className="h-6 w-6 text-muted-foreground hover:text-foreground"
            onClick={handleNext}
            aria-label="Next Tip"
          >
            <ChevronRight className="h-3.5 w-3.5" />
          </Button>
        </div>
      </div>

      {/* Tip Content */}
      <div className="space-y-1.5 min-h-[85px] transition-all duration-300">
        <div className="flex items-center gap-1.5">
          <TipIcon className="h-3.5 w-3.5 text-primary" />
          <h4 className="text-xs font-bold text-foreground">{currentTip.title}</h4>
        </div>
        <p className="text-xs text-muted-foreground leading-relaxed">
          {currentTip.text}
        </p>
      </div>

      {/* Pagination Dots */}
      <div className="flex items-center justify-center gap-1 pt-1">
        {ROTATING_TIPS.map((tip, idx) => (
          <button
            key={tip.id}
            onClick={() => setCurrentIndex(idx)}
            className={`h-1.5 rounded-full transition-all duration-300 ${
              idx === currentIndex
                ? 'w-5 bg-primary'
                : 'w-1.5 bg-muted-foreground/30 hover:bg-muted-foreground/60'
            }`}
            aria-label={`Jump to tip ${idx + 1}`}
          />
        ))}
      </div>
    </div>
  )
}
